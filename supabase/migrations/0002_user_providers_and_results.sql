-- ============================================================================
--  Tuton Agent - provider per akun, hasil di Storage, cookie terenkripsi
-- ============================================================================
--  Jalankan SEKALI di Supabase Dashboard -> SQL Editor, SETELAH 0001.
--  Aman dijalankan ulang (semua pernyataan idempotent).
--
--  Isi:
--   1. `user_providers`  - provider OpenAI-compatible + model per agent per
--      akun. Sebelumnya berkas `runtime/runtime.json` bersama, sehingga satu
--      user memakai API key user lain.
--   2. Storage privat `results` + `user_results` - metadata DOCX hasil
--      pipeline. Objek disimpan di path `<user_id>/<matkul>/<sesi>/<berkas>`,
--      jadi akun hanya bisa menjangkau path miliknya sendiri.
--   3. Catatan enkripsi cookie Moodle: kolom `cookie_moodle` sekarang berisi
--      token Fernet (`v1:...`), bukan nilai mentah. Enkripsi/dekripsi
--      dilakukan `tuton/crypto.py` dengan `COOKIE_ENCRYPTION_KEY` dari `.env`;
--      kuncinya TIDAK disimpan di database.
-- ============================================================================

-- ------------------------------------------------------- 1. provider per akun
create table if not exists public.user_providers (
  user_id     text primary key,

  -- Bentuk JSON-nya sama dengan runtime.json lama:
  --   providers: [{id, name, base_url, api_key, models: [..]}]
  --   agents:    {scrapper|research|vision|worker: "provider/model"}
  providers   jsonb not null default '[]'::jsonb,
  agents      jsonb not null default '{}'::jsonb,

  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

comment on table public.user_providers is
  'Provider OpenAI-compatible dan model per agent milik satu akun. Berisi API key; hanya service key yang boleh membaca.';

alter table public.user_providers enable row level security;
-- Tidak ada policy: anon/authenticated tidak boleh melihat API key siapa pun.
revoke all on public.user_providers from anon, authenticated;

drop trigger if exists user_providers_touch on public.user_providers;
create trigger user_providers_touch
  before update on public.user_providers
  for each row execute function public.tuton_touch_updated_at();

-- --------------------------------------------------- 2. hasil: bucket + metadata
-- Bucket privat: tidak ada policy Storage, jadi hanya service key (server
-- Python) yang bisa membaca/menulis. Browser tidak pernah diberi URL publik;
-- unduhan selalu lewat server yang memeriksa kepemilikan baris.
insert into storage.buckets (id, name, public, file_size_limit)
values ('results', 'results', false, 52428800)
on conflict (id) do update set public = false;

create table if not exists public.user_results (
  id            bigint generated by default as identity primary key,
  user_id       text not null,
  slug          text not null,
  sesi          text not null,
  nama          text not null,

  -- Path objek di bucket `results`: <user_id>/<slug>/<sesi>/<nama>.
  -- Disimpan eksplisit supaya unduh/hapus tidak perlu menyusun ulang path.
  storage_path  text not null,
  ukuran        bigint not null default 0,

  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),

  constraint user_results_path_unique unique (user_id, storage_path)
);

comment on table public.user_results is
  'Metadata DOCX hasil pipeline. Berkasnya sendiri di bucket Storage privat `results`.';

create index if not exists user_results_user_updated_idx
  on public.user_results (user_id, updated_at desc);

alter table public.user_results enable row level security;
revoke all on public.user_results from anon, authenticated;

drop trigger if exists user_results_touch on public.user_results;
create trigger user_results_touch
  before update on public.user_results
  for each row execute function public.tuton_touch_updated_at();

-- --------------------------------------------------------------- 3. catatan
-- Kolom `user_identities.cookie_moodle` tidak diubah tipenya (text), hanya
-- isinya: token `v1:<fernet>` hasil `tuton/crypto.py`. Nilai plaintext lama
-- dibaca sekali oleh server lalu ditulis ulang dalam bentuk terenkripsi.
comment on column public.user_identities.cookie_moodle is
  'Cookie MoodleSession terenkripsi (Fernet, awalan v1:). Kunci: COOKIE_ENCRYPTION_KEY di .env server, bukan di database.';
